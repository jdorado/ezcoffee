const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const source = fs.readFileSync(path.resolve(__dirname, '../coffee_app/src/main.tsx'), 'utf8')
assert.match(source, /encodeURIComponent\(key\).*\/retry/)
assert.match(source, /className="message-retry"/)
assert.match(source, /aria-label="Retry message"/)
assert.doesNotMatch(source, /replace\(.*assistant-failed/)
assert.match(source, /coffee_id:selected\|\|null,shot_date:today\(\)/)
assert.match(source, /setInterval\(poll,1000\)/)
console.log('Chat retry: failed replies expose a bounded retry action and turns poll to completion.')
